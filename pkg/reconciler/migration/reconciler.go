var (
	logger = ctrl.Log.WithName("migration")
)

// MigrationReconciler adds the 'app.kubernetes.io/part-of=che.eclipse.org' label
// to objects created before the operator's labeling scheme was introduced.
//
// The label is required because the operator's k8s client cache (see getCacheFunc in cmd/main.go)
// only watches objects labeled with 'app.kubernetes.io/part-of=che.eclipse.org'. Objects created
// before this labeling scheme was introduced are invisible to the cached client, and thus to the
// operator, until the label is added.
//
// Early versions of this migration also ran broad label-selector sweeps (by 'app.kubernetes.io/instance'
// and 'app' labels) across many resource types to relabel objects from very old installations. Those phases
// were dropped: they existed only to cover clusters upgrading from those first versions.
// Only named objects known to the current operator are migrated.
type MigrationReconciler struct {
	reconciler.Reconcilable
}

func NewReconciler() *MigrationReconciler {
	return &MigrationReconciler{}
}

func (r *MigrationReconciler) Reconcile(cheCtx *chetypes.CheContext) (reconcile.Result, bool, error) {
	err := r.migrateKnownObjects(cheCtx)
	if err != nil {
		return reconcile.Result{},
			false,
			fmt.Errorf("failed to migrate labels: %w", err)
	}

	return reconcile.Result{}, true, nil
}

func (r *MigrationReconciler) Finalize(_ *chetypes.CheContext) error {
	return nil
}

// migrateKnownObjects migrates objects that are known by name — referenced in the CheCluster
// spec or by well-known constants. Most of them are autogenerated and do not require migration,
// but some may have been created manually or by an older operator version, so each one is checked.
func (r *MigrationReconciler) migrateKnownObjects(cheCtx *chetypes.CheContext) error {
	if err := r.migrateSelfSignedCertificateSecret(cheCtx); err != nil {
		return err
	}

	if err := r.migrateCaBundleConfigMap(cheCtx); err != nil {
		return err
	}

	if err := r.migrateTlsSecret(cheCtx); err != nil {
		return err
	}

	if err := r.migrateConsoleLink(cheCtx); err != nil {
		return err
	}

	if err := r.migrateProxyCredentialsSecret(cheCtx); err != nil {
		return err
	}

	if err := r.migrateGitTrustedCertsConfigMap(cheCtx); err != nil {
		return err
	}

	return nil
}

func (r *MigrationReconciler) migrateSelfSignedCertificateSecret(cheCtx *chetypes.CheContext) error {
	key := client.ObjectKey{
		Name:      constants.SelfSignedCertificateSecretName,
		Namespace: cheCtx.CheCluster.Namespace,
	}

	return r.migrateObject(cheCtx, key, &corev1.Secret{})
}

func (r *MigrationReconciler) migrateCaBundleConfigMap(cheCtx *chetypes.CheContext) error {
	key := client.ObjectKey{
		Name:      constants.DefaultCaBundleCertsCMName,
		Namespace: cheCtx.CheCluster.Namespace,
	}

	return r.migrateObject(cheCtx, key, &corev1.ConfigMap{})
}

func (r *MigrationReconciler) migrateTlsSecret(cheCtx *chetypes.CheContext) error {
	tlsSecretName := utils.ValueOrDef(
		cheCtx.CheCluster.Spec.Networking.TlsSecretName,
		constants.DefaultCheTLSSecretName,
	)
	key := client.ObjectKey{
		Name:      tlsSecretName,
		Namespace: cheCtx.CheCluster.Namespace,
	}

	return r.migrateObject(cheCtx, key, &corev1.Secret{})
}

func (r *MigrationReconciler) migrateConsoleLink(cheCtx *chetypes.CheContext) error {
	if !infrastructure.IsConsoleLinkEnabled() {
		return nil
	}

	key := client.ObjectKey{Name: defaults.GetConsoleLinkName()}

	return r.migrateObject(cheCtx, key, &consolev1.ConsoleLink{})
}

func (r *MigrationReconciler) migrateProxyCredentialsSecret(cheCtx *chetypes.CheContext) error {
	proxy := ptr.Deref(cheCtx.CheCluster.Spec.Components.CheServer.Proxy, chev2.Proxy{})
	secretName := utils.ValueOrDef(proxy.CredentialsSecretName, constants.DefaultProxyCredentialsSecret)

	key := client.ObjectKey{
		Name:      secretName,
		Namespace: cheCtx.CheCluster.Namespace,
	}

	return r.migrateObject(cheCtx, key, &corev1.Secret{})
}

func (r *MigrationReconciler) migrateGitTrustedCertsConfigMap(cheCtx *chetypes.CheContext) error {
	trustedCerts := ptr.Deref(cheCtx.CheCluster.Spec.DevEnvironments.TrustedCerts, chev2.TrustedCerts{})
	cmName := utils.ValueOrDef(trustedCerts.GitTrustedCertsConfigMapName, constants.DefaultGitSelfSignedCertsConfigMapName)

	key := client.ObjectKey{
		Name:      cmName,
		Namespace: cheCtx.CheCluster.Namespace,
	}

	return r.migrateObject(cheCtx, key, &corev1.ConfigMap{})
}

func (r *MigrationReconciler) migrateObject(cheCtx *chetypes.CheContext, key client.ObjectKey, obj client.Object) error {
	cw := cheCtx.ClusterAPI.NonCachingClientWrapper

	exists, err := cw.GetIgnoreNotFound(cheCtx.Context, key, obj)
	if !exists {
		return err
	}

	labels := utils.NonNilMap(obj.GetLabels())
	if labels[constants.KubernetesPartOfLabelKey] == constants.CheEclipseOrg {
		return nil
	}

	labels[constants.KubernetesPartOfLabelKey] = constants.CheEclipseOrg
	obj.SetLabels(labels)

	opts := &clientwrapper.SyncOptions{
		SuppressDiff: true,
	}
	if err := cw.Sync(cheCtx.Context, obj, opts); err != nil {
		return err
	}

	logger.Info("Migrated object to be visible to the operator's cached client",
		"kind", clientwrapper.GetObjectType(obj), "namespace", key.Namespace, "name", key.Name)

	return nil
}
